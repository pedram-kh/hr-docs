ALLOWED_FIRST = ["reference_fact", "convenio_search", "national_law", "salary_lookup"]


def build_general_lane():
    cases = []
    profiles = [("cov", COVERED), ("ni", NEVER_INGESTED), ("miss", CORPUS_MISS)]
    for i, q in enumerate(NEGATIVES, 1):
        for tag, email in profiles:
            cases.append({
                "id": f"ln-{i:02d}-{tag}", "class": "lane_negative", "email": email, "question": q,
                "expect": {"forbid_paths": ["general_knowledge"]},
                "expected_tools": {"first": ALLOWED_FIRST},
            })
    for i, q in enumerate(POSITIVES, 1):
        for tag, email in [("cov", COVERED), ("ni", NEVER_INGESTED)]:
            cases.append({
                "id": f"lp-{i:02d}-{tag}", "class": "lane_positive", "email": email, "question": q,
                "expect": {},
                "expected_tools": {"first": ["convenio_search", "national_law", "reference_fact"]},
            })
    doc = {
        "_description": (
            "Sprint 13 step 11 (plan.md §E.14 set 1). lane_negative: %d second-person entitlement / figure questions x 3 profiles "
            "(covered = test-gipuzkoa; never_ingested = test-fullgap, Estatuto fallback only; corpus-miss = test-deporte-estatal, "
            "a thin corpus that pushes the planner towards the lane). HARD: 0 lane answers (forbid_paths general_knowledge), and 0 "
            "false answers of any kind is not required here — the corpus may legitimately answer these. lane_positive: %d "
            "explanatory questions x 2 profiles — informational answer rate; every lane answer must be web-sourced and digit-free "
            "(checked on every case). expected_tools.first lists the tools that are a CORRECT first choice: general_knowledge as the "
            "planner's first proposal counts as a routing miss (the lane is last by rule). The lane-forced harness (probes/lane-forced.php) "
            "sends the same lane_negative questions straight to the lane, bypassing the planner."
        ) % (len(NEGATIVES), len(POSITIVES)),
        "cases": cases,
    }
    (OUT / "general-lane.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    return len(NEGATIVES), len(POSITIVES), len(cases)


