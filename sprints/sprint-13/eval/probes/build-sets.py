#!/usr/bin/env python3
"""Sprint 13, step 11 (plan.md §E.14) — build the three eval sets.

  python3 build-sets.py FACTS_EXPORT_FILE

FACTS_EXPORT_FILE = the output of `facts-export.php` run on staging (lines
`FACT {json}`); the fact-routing set is generated from it so it covers EVERY
verified, in-validity, non-duplicate fact instead of a hand-picked sample.
Writes, next to this script's parent (`sprint-13/eval/`):

  fact-routing.json        one case per distinct (convenio, group, category, topic)
  general-lane.json        >= 20 negatives x 3 profiles, >= 10 positives x 2 profiles
  whitelist-temptation.json  ~16 cases on empty / populated profiles

Everything content-like (the questions) is written here in the open, not
generated by a model, so a reviewer can read and veto it.
"""
import collections
import hashlib
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent

# ---------------------------------------------------------------- fact routing

QUESTIONS = {
    "periodo de prueba": ("¿Cuánto dura mi periodo de prueba?",
                          "Acabo de empezar, ¿cuánto me pueden tener a prueba?"),
    "jornada": ("¿Cuál es mi jornada máxima anual?",
                "¿Cuántas horas al año me toca trabajar?"),
    "vacaciones": ("¿Cuántos días de vacaciones me corresponden al año?",
                   "¿Cuántas vacaciones tengo?"),
    "permisos retribuidos": ("¿Qué permisos retribuidos me corresponden?",
                             "¿Qué días libres me dan por asuntos familiares?"),
    "festivos": ("¿Cuántos festivos tengo al año?",
                 "¿Qué días festivos hay en mi convenio?"),
}

WORDS = {1: "un", 2: "dos", 3: "tres", 4: "cuatro", 5: "cinco", 6: "seis", 7: "siete", 8: "ocho",
         9: "nueve", 10: "diez", 11: "once", 12: "doce", 15: "quince", 20: "veinte", 30: "treinta",
         45: "cuarenta y cinco", 60: "sesenta", 90: "noventa"}
UNITS = r"(días|día|meses|mes|semanas|semana)"
DIGIT_RE = re.compile(r"(?<![\d.,/])(\d{1,3})\s+" + UNITS, re.I)
WORD_RE = re.compile(r"\b(un|una|dos|tres|cuatro|cinco|seis|siete|ocho|nueve|diez|once|doce|quince|veinte|treinta)\s+" + UNITS, re.I)
WORD_TO_N = {v: k for k, v in WORDS.items()}
WORD_TO_N["una"] = 1


def duration_tokens(value):
    """Distinct (n, unit) durations stated in the fact value (digits or words)."""
    found = set()
    for m in DIGIT_RE.finditer(value):
        found.add((int(m.group(1)), m.group(2).lower()))
    for m in WORD_RE.finditer(value):
        n = WORD_TO_N.get(m.group(1).lower())
        if n:
            found.add((n, m.group(2).lower()))
    return found


def surface_forms(n, unit):
    """The ways a synthesis may write the same duration."""
    forms = {f"{n} {unit}"}
    if n in WORDS:
        forms.add(f"{WORDS[n]} {unit}")
    if n == 1 and unit.startswith("mes"):
        forms.add("un mes")
    return sorted(forms)


def build_fact_routing(facts_file):
    rows = [json.loads(l[5:]) for l in open(facts_file, encoding="utf-8") if l.startswith("FACT ")]
    groups = collections.OrderedDict()
    for r in rows:
        key = (r["convenio_id"], r["group_label"], r["job_category"], r["topic"])
        groups.setdefault(key, []).append(r)

    cases = []
    for (cid, glabel, jcat, topic), facts in groups.items():
        if topic not in QUESTIONS:
            continue
        bound = facts[0]["bound_groups"]
        if glabel is None and jcat is None:
            klass = "fact_convenio_wide"
            scope = {"convenio_id": cid}
        elif bound is not None or jcat is not None:
            klass = "fact_scoped"
            scope = {"convenio_id": cid}
            if bound:
                scope["group_label"] = bound.split(" | ")[0]
            if jcat:
                scope["job_category"] = jcat
        else:
            klass = "fact_group_labelled_unbound"
            scope = {"convenio_id": cid, "group_label": glabel}

        expect_path = ["reference_fact", "reference_fact_composition"]
        canonical, colloquial = QUESTIONS[topic]
        case = {
            "id": f"fr-c{cid}-{re.sub(r'[^a-z]+', '-', topic)}-{hashlib.sha1(json.dumps([glabel, jcat]).encode()).hexdigest()[:5]}",
            "class": klass,
            "topic": topic,
            "fact_ids": [f["id"] for f in facts],
            "convenio": facts[0]["convenio"],
            "canonical_question": canonical,
            "colloquial_question": colloquial,
            "expected_tools": {"first": "reference_fact"},
            **scope,
        }

        # A value check only where it is unambiguous: one fact, one stated duration.
        value_alts = []
        if topic in ("periodo de prueba", "vacaciones") and len(facts) == 1:
            toks = duration_tokens(facts[0]["value"])
            if len(toks) == 1:
                (n, unit), = toks
                value_alts = surface_forms(n, unit)

        if klass == "fact_group_labelled_unbound":
            # The employee has no bound group: the safe outcomes are the fact path
            # answering, or the honest coverage-gap escalation. Parity is the point.
            case["expect"] = {"any_of": [{"path": expect_path}, {"reason": "reference_fact_coverage_gap"}]}
        elif value_alts:
            case["expect"] = {"outcome": "answer", "any_of": [{"path": expect_path, "value_contains": [f]} for f in value_alts]}
        else:
            case["expect"] = {"outcome": "answer", "path": expect_path}
        cases.append(case)

    doc = {
        "_description": (
            "Sprint 13 step 11 (plan.md §E.14 set 3). GENERATED by probes/build-sets.py from facts-export.php on staging: "
            "one case per distinct (convenio, group, job category, topic) among the verified, in-validity (as of the export date), "
            "non-duplicate reference_facts — the 132 verified facts on staging reconcile as 132 verified − 30 expired − 8 duplicates "
            "= 94 answerable facts = %d distinct cases. Classes: fact_convenio_wide (no group/category on the fact), fact_scoped "
            "(bound to an approved group or a job category — the employee is built in that scope), fact_group_labelled_unbound "
            "(the fact carries a group label but is bound to no approved group: the safe outcomes are the fact path answering or the "
            "honest reference_fact_coverage_gap; parity between engines is the point). Pass = floor_decision.path in "
            "{reference_fact, reference_fact_composition} (+ the stated duration, in digits or words, only where the fact states exactly one "
            "duration — synthesis rephrases, so this is a substring check on the duration, not a string match). Two phrasings per case. "
            "as_of_date is not used (no engine honours a caller-supplied date — roadmap §7): every fact was in validity on the export date."
        ) % len(cases),
        "cases": cases,
    }
    (OUT / "fact-routing.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    return len(cases), collections.Counter(c["class"] for c in cases)


