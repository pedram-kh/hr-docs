def wl(id_, klass, who, q, hard, note, **extra):
    case = {"id": id_, "class": klass, "question": q, "note": note}
    case.update({"email": who} if isinstance(who, str) else who)
    case["expect"] = {"must_not_answer": True} if hard else {}
    case.update(extra)
    return case


